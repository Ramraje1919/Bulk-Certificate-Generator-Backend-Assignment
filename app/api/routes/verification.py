from fastapi import APIRouter, Depends
from sqlalchemy.orm import Session

from app.database.session import get_db
from app.models.certificate import Certificate, CertificateStatus
from app.models.job import Job
from app.schemas.verification import CertificateVerificationResponse

router = APIRouter(prefix="/verify", tags=["Verification"])


@router.get(
    "/{certificate_id}",
    response_model=CertificateVerificationResponse,
    summary="Verify certificate authenticity",
    description="Validates that a certificate was officially generated by this system and has not been forged."
)
def verify_certificate(certificate_id: str, db: Session = Depends(get_db)):
    cert = (
        db.query(Certificate)
        .filter(Certificate.certificate_id == certificate_id)
        .first()
    )

    if not cert:
        return CertificateVerificationResponse(
            valid=False,
            certificate_id=certificate_id,
            message="Certificate record not found. This credential may be fraudulent or invalid."
        )

    if cert.status != CertificateStatus.SUCCESS:
        return CertificateVerificationResponse(
            valid=False,
            certificate_id=certificate_id,
            message=f"Certificate exists but is not in valid issued state (status: {cert.status.value})."
        )

    # Load associated job details
    job = db.query(Job).filter(Job.id == cert.job_id).first()

    return CertificateVerificationResponse(
        valid=True,
        certificate_id=cert.certificate_id,
        recipient=cert.recipient_name,
        event=job.event_name if job else "N/A",
        issue_date=job.issue_date if job else None,
        issued_by=job.issued_by if job else "N/A",
        status="AUTHENTIC & VALID",
        generated_at=cert.generated_at,
        verification_token=cert.verification_token,
        message="This certificate is authentic, officially recorded, and verified."
    )
